def _install_wrapper(profile: str, packager_raw: str, product_raw: str | None = None) -> str:
    if product_raw:
        product_default = product_raw.rstrip("/")
        pc_default = f"{product_default}/packageconfig.yaml"
    else:
        product_default = "$SCRIPT_DIR"
        pc_default = "$SCRIPT_DIR/packageconfig.yaml"
    return f"""#!/usr/bin/env bash
# wget install — profile {profile}. Generated by vibed-infra package.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]:-$0}}")" && pwd)"
PACKAGER_RAW="${{PACKAGER_RAW:-{packager_raw}}}"
export PACKAGER_RAW
export PRODUCT_RAW="${{PRODUCT_RAW:-{product_default}}}"
export PACKAGECONFIG_URL="${{PACKAGECONFIG_URL:-{pc_default}}}"
export INFRA_PROFILE={profile}
export INSTALL_DIR="${{INSTALL_DIR:-.}}"
if [[ "$PACKAGER_RAW" =~ ^/ ]]; then
  exec bash "$PACKAGER_RAW/install.sh" --profile {profile}
fi
if command -v curl >/dev/null 2>&1; then
  exec bash <(curl -fsSL "${{PACKAGER_RAW}}/install.sh") --profile {profile}
else
  exec bash <(wget -qO- "${{PACKAGER_RAW}}/install.sh") --profile {profile}
fi
"""


def build_dist(
    product_dir: Path,
    out_dir: Path,
    packager_root: Path,
    *,
    raw_base: str | None = None,
    packager_raw: str | None = None,
) -> None:
    product_dir = product_dir.resolve()
    out_dir = out_dir.resolve()
    packager_root = packager_root.resolve()

    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    product = load_product(product_dir)
    tpl = product["templates_dir"]
    # Default local paths; pass http(s) raw_base/packager_raw for wget|bash installs.
    raw_base_val = (raw_base if raw_base is not None else str(out_dir)).rstrip("/")
    packager_raw_val = (
        packager_raw if packager_raw is not None else str(packager_root)
    ).rstrip("/")

    conf = compile_packageconfig(
        product,
        raw_base=raw_base_val,
        packager_raw=packager_raw_val,
    )
    meta = conf["_meta"]
    comps = product["components"]
    sites = conf["profiles"]["gateway"].get("sites") or []

    # Copy source configs into dist
    shutil.copy2(tpl / "vibed-infra-config.yml", out_dir / "vibed-infra-config.yml")
    refs = product["infra"].get("templates") or {}
    for dst, key in (
        ("api-config.yaml", "api"),
        ("ui-config.yaml", "ui"),
        ("nodes-config.yaml", "nodes"),
    ):
        src_name = refs.get(key) or f"{key}-config.yaml"
        shutil.copy2(tpl / src_name, out_dir / dst)

    _write(out_dir / "packageconfig.yaml", dump_yaml(conf))

    write_app_config(comps["api"], out_dir / "api-app.yaml")
    write_app_config(comps["nodes"], out_dir / "nodes-workers.yaml")

    _write(out_dir / ".env.api.example", _env_api(meta, conf, comps["api"]))
    _write(out_dir / ".env.ui.example", _env_ui(meta, conf, comps["ui"]))
    _write(out_dir / ".env.nodes.example", _env_nodes(meta, conf, comps["nodes"]))
    _write(out_dir / ".env.gateway.example", _env_gateway(meta, conf, sites))
    _write(out_dir / "docker-compose.workers.yml", _compose_workers(meta, conf))

    gw_dir = out_dir / "gateway"
    gw_dir.mkdir()
    shutil.copy2(packager_root / "templates" / "generic" / "gateway" / "nginx.conf", gw_dir / "nginx.conf")

    for script in (
        "start-api.sh",
        "start-ui.sh",
        "start-nodes.sh",
        "start-gateway.sh",
        "update-api.sh",
        "update-ui.sh",
        "update-nodes.sh",
        "update-gateway.sh",
        "gen-dev-certs.sh",
    ):
        _copy_generic(packager_root, out_dir, script)

    sidecar = packager_root / "templates" / "persist-logs" / "start-persist-sidecar.sh"
    if sidecar.is_file():
        shutil.copy2(sidecar, out_dir / "start-persist-sidecar.sh")
        _chmod_x(out_dir / "start-persist-sidecar.sh")

    # Bake HTTP URLs into install wrappers when packaging for wget serve; else GitHub default.
    if packager_raw_val.startswith("http://") or packager_raw_val.startswith("https://"):
        wrapper_packager = packager_raw_val
    else:
        wrapper_packager = "https://raw.githubusercontent.com/naiemk/vibed-infra/main"
    wrapper_product = (
        raw_base_val
        if raw_base_val.startswith("http://") or raw_base_val.startswith("https://")
        else None
    )
    notify_src = packager_root / "github" / "notify-vps-pull.py"
    if notify_src.is_file():
        shutil.copy2(notify_src, out_dir / "notify-vps-pull.py")
        _chmod_x(out_dir / "notify-vps-pull.py")

    for profile in ("api", "ui", "nodes", "gateway"):
        name = f"install-{profile}.sh"
        _write(
            out_dir / name,
            _install_wrapper(profile, wrapper_packager, wrapper_product),
            executable=True,
        )

    _write(
        out_dir / "DNS-SKILL.md",
        _dns_skill(
            meta.get("productName") or conf.get("name") or "app",
            sites,
            public_ip=str(meta.get("publicIp") or conf["profiles"]["gateway"].get("publicIp") or ""),
        ),
    )

    readme = f"""# dist — generated by vibed-infra package

Do not edit by hand. Run `../package.sh` from the product root and commit.

## VPS install

```bash
wget -qO- https://raw.githubusercontent.com/ORG/REPO/main/dist/install-api.sh | bash
wget -qO- https://raw.githubusercontent.com/ORG/REPO/main/dist/install-ui.sh | bash
wget -qO- https://raw.githubusercontent.com/ORG/REPO/main/dist/install-nodes.sh | bash
wget -qO- https://raw.githubusercontent.com/ORG/REPO/main/dist/install-gateway.sh | bash
```

Network: `{meta['network']}` (shared host edge). API container: `{meta['apiContainer']}`.
Gateway install bootstraps `~/services/gateway` once, then drops `apps/{{product}}/sites.conf`.

## Image updates

wget install registers this product with the machine update-agent. A GHCR `:main` push (reusable workflow + `id-token: write`) POSTs `/_vibed/hooks/ghcr` so the VPS pulls immediately. Cron `*_AUTO_UPDATE` is a backup. See the packager’s infra-update-agent skill.

## DNS (AU agent)

Copy [`DNS-SKILL.md`](DNS-SKILL.md) into an AU agent browser extension. Domains and `gateway.publicIp` are baked in when configured; confirm the IP with the operator.
"""
    _write(out_dir / "README.md", readme)
    print(f"packaged: {out_dir}")


def main() -> int:
    ap = argparse.ArgumentParser(description="Build product dist/ for VPS wget install")
    ap.add_argument("--product", required=True, help="Product root (contains templates/)")
    ap.add_argument("--out", required=True, help="Output dist directory")
    ap.add_argument(
        "--packager",
        default=str(Path(__file__).resolve().parent.parent),
        help="vibed-infra root",
    )
    ap.add_argument(
        "--raw-base",
        default=None,
        help="packageconfig rawBase + PRODUCT_RAW default (path or http URL)",
    )
    ap.add_argument(
        "--packager-raw",
        default=None,
        help="packageconfig packagerRaw + PACKAGER_RAW default (path or http URL)",
    )
    args = ap.parse_args()
    build_dist(
        Path(args.product),
        Path(args.out),
        Path(args.packager),
        raw_base=args.raw_base,
        packager_raw=args.packager_raw,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
