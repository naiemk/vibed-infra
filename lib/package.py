def _env_gateway(meta: dict, conf: dict, sites: list) -> str:
    au = conf["profiles"]["gateway"]["autoUpdate"]
    gw = conf["profiles"]["gateway"]
    # Host gateway stores PEMs under ./certs (setup-tls.sh). tlsCertDir is legacy/docs only
    # unless it already points at a relative ./certs tree.
    cert_dir = "./certs"
    if sites:
        raw = sites[0].get("tlsCertDir") or ""
        if raw.startswith("./certs") or raw.rstrip("/") == "certs":
            cert_dir = raw.rstrip("/")
    flags = au.get("flags") or ["GATEWAY_AUTO_UPDATE"]
    flag_lines = "\n".join(f"{f}=0" for f in flags)
    public_ip = gw.get("publicIp") or meta.get("publicIp") or ""
    tls_email = gw.get("tlsEmail") or meta.get("tlsEmail") or ""
    return f"""# Generated by vibed-infra package — thin product wrapper; host lives in GATEWAY_HOME
DOCKER_NETWORK={meta['network']}
GATEWAY_NAME={meta['gatewayContainer']}
GATEWAY_HOME=~/services/gateway
NGINX_IMAGE={conf['images']['nginx']}
TLS_FULLCHAIN={cert_dir}/fullchain.pem
TLS_PRIVKEY={cert_dir}/privkey.pem
TLS_MODE=
TLS_EMAIL={tls_email}
GATEWAY_PUBLIC_IP={public_ip}
CERTBOT_WWW=./certbot-www
HTTP_PORT=80
HTTPS_PORT=443
GATEWAY_MEMORY_LIMIT=64m
{flag_lines}
{au.get('intervalEnv', 'GATEWAY_AUTO_UPDATE_INTERVAL_MIN')}=20
{au.get('stopTimeoutEnv', 'GATEWAY_STOP_TIMEOUT')}=30
DOCKER_AUTO_PRUNE=1
DOCKER_PRUNE_UNUSED=0
DOCKER_PRUNE_UNTIL=72h
"""


def _dns_skill(product_name: str, sites: list, public_ip: str = "") -> str:
    tmpl = (
        Path(__file__).resolve().parent.parent
        / "templates"
        / "generic"
        / "DNS-SKILL.md.tmpl"
    )
    text = tmpl.read_text(encoding="utf-8")
    ip = (public_ip or "").strip()
    value = ip if ip else "{{VPS_IP}}"
    lines: list[str] = []
    for site in sites:
        host = site["host"]
        lines.append(f"| `{host}` | A | `{value}` |")
        for alias in site.get("aliases") or []:
            lines.append(f"| `{alias}` | A | `{value}` |")
    table = "| Hostname | Type | Value |\n|----------|------|-------|\n" + "\n".join(lines)
    if not lines:
        table = "_No gateway.sites[] configured — add hosts in vibed-infra-config.yml and re-package._"
    if ip:
        ip_instruction = (
            f"Confirm IPv4 `{ip}` with the operator before changing records — do not invent a different IP."
        )
        before_steps = f"""1. **Confirm the VPS public IPv4 is `{ip}`** (from `gateway.publicIp` in product config). If the operator says the IP changed, use their new IP and ask them to update config / re-package.
2. Optionally ask for IPv6 if they want AAAA records.
3. Confirm which DNS provider UI they use (Cloudflare, registrar, Route53, etc.).
4. Ensure you are logged into that provider in the browser before editing records."""
        ip_safety = f"\n- The packaged IP is `{ip}`; only change it if the operator confirms a new address."
    else:
        ip_instruction = "Ask the user for the VPS IPv4 address first — never invent an IP."
        before_steps = """1. **Ask the user for the VPS public IPv4 address.** Do not guess or invent IPs.
2. Optionally ask for IPv6 if they want AAAA records.
3. Confirm which DNS provider UI they use (Cloudflare, registrar, Route53, etc.).
4. Ensure you are logged into that provider in the browser before editing records.

Placeholder used below: `{{VPS_IP}}` — replace with the IPv4 the user gives you."""
        ip_safety = ""
    return (
        text.replace("{{PRODUCT_NAME}}", product_name)
        .replace("{{DNS_RECORDS}}", table)
        .replace("{{IP_INSTRUCTION}}", ip_instruction)
        .replace("{{BEFORE_STEPS}}", before_steps)
        .replace("{{IP_SAFETY}}", ip_safety)
    )

